#!/usr/bin/env node
// Generate deploy/.env.production without printing any secret values.
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { randomBytes } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const target = path.join(here, '.env.production')
const force = process.argv.includes('--force')

if (existsSync(target) && !force) {
  console.log(`${target} already exists; not overwriting (use --force)`)
  process.exit(0)
}

let firebase = {
  projectId: process.env.RIGEL_FIREBASE_PROJECT_ID || '',
  apiKey: process.env.RIGEL_FIREBASE_API_KEY || '',
  authDomain: process.env.RIGEL_FIREBASE_AUTH_DOMAIN || '',
}
const builtConfig = path.join(root, '.deploy', 'app', 'config.js')
if (existsSync(builtConfig)) {
  const text = readFileSync(builtConfig, 'utf8')
  const match = text.match(/window\.RIGEL_CONFIG\s*=\s*(\{[\s\S]*\});/)
  if (match) {
    try {
      const parsed = JSON.parse(match[1])
      firebase = {
        projectId: parsed.projectId || firebase.projectId,
        apiKey: parsed.apiKey || firebase.apiKey,
        authDomain: parsed.authDomain || firebase.authDomain,
      }
    } catch {
      // Leave the environment values in place; check.mjs reports the gap.
    }
  }
}

const hex = (bytes) => randomBytes(bytes).toString('hex')
const token = (bytes) => randomBytes(bytes).toString('base64url')
const mailFrom = 'Rigel <hello@askrigel.com>'
const values = {
  COMPOSE_PROJECT_NAME: 'rigel',
  ACME_EMAIL: 'hello@askrigel.com',
  POSTGRES_USER: 'rigel',
  POSTGRES_PASSWORD: hex(32),
  POSTGRES_DB: 'rigel',
  POSTGRES_CMS_DB: 'rigel_cms',
  JWT_SECRET: hex(48),
  ACCESS_TOKEN_MINUTES: '15',
  REFRESH_TOKEN_DAYS: '30',
  APP_URL: 'https://askrigel.com',
  API_URL: 'https://api.askrigel.com',
  ALLOWED_ORIGINS: 'https://askrigel.com,https://www.askrigel.com,https://admin.askrigel.com',
  RESEND_API_KEY: '',
  MAIL_FROM: mailFrom,
  CONTACT_TO: 'hello@askrigel.com',
  DATA_DIR: '/data',
  DATABASE_SSL: 'false',
  LLM_BASE_URL: '',
  LLM_API_KEY: '',
  LLM_PROVIDER: 'openrouter',
  LLM_MODELS: '',
  LLM_INPUT_MICROS_PER_MILLION: '500000',
  LLM_OUTPUT_MICROS_PER_MILLION: '1500000',
  LLM_DAILY_MICROS: '2000000',
  LLM_MAX_OUTPUT_TOKENS: '8192',
  GRAVITY_API_KEY: '',
  GRAVITY_PRODUCTION: 'false',
  TURNSTILE_SECRET: '',
  ENROLL_TOKEN: '',
  REQUIRE_DEVICE: 'false',
  RIGEL_RELAY_TOKEN: token(32),
  MUSE_RELAY_TOKEN: token(32),
  PAYLOAD_SECRET: hex(32),
  PAYLOAD_PUBLIC_SERVER_URL: 'https://admin.askrigel.com',
  PAYLOAD_ADMIN_EMAIL: 'hello@askrigel.com',
  PAYLOAD_ADMIN_PASSWORD: hex(24),
  RIGEL_FIREBASE_PROJECT_ID: firebase.projectId,
  RIGEL_FIREBASE_API_KEY: firebase.apiKey,
  RIGEL_FIREBASE_AUTH_DOMAIN:
    firebase.authDomain || (firebase.projectId ? `${firebase.projectId}.firebaseapp.com` : ''),
  RIGEL_CMS_URL: '',
  TZ: 'UTC',
}

const quote = (key, value) => {
  const text = String(value)
  return /[\s#"'$]/.test(text) ? `${key}=${JSON.stringify(text)}` : `${key}=${text}`
}

const lines = [
  '# Generated by deploy/init-env.mjs. Gitignored; never commit this file.',
  '# Optional external credentials (Resend, LLM, Gravity) are blank until provided.',
  '',
]
for (const [key, value] of Object.entries(values)) lines.push(quote(key, value))
lines.push('')

writeFileSync(target, lines.join('\n'), { mode: 0o600 })
try {
  chmodSync(target, 0o600)
} catch {
  // Windows does not implement POSIX modes; the file is still outside version control.
}
console.log(`wrote ${target}`)
if (!values.RIGEL_FIREBASE_PROJECT_ID || !values.RIGEL_FIREBASE_API_KEY) {
  console.warn('Firebase web config is missing; set RIGEL_FIREBASE_* before building the site.')
}
