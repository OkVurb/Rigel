#!/usr/bin/env node
/**
 * Assemble the deploy directory for Firebase Hosting.
 *
 * Two things happen here that must not happen by hand:
 *
 *  1. `web/app/config.js` is generated from the environment or `cloud.json`. The project id
 *     belongs to whoever deploys, so it is never committed.
 *  2. Every CSS and JS reference in the HTML gets a content hash (`?v=…`). Without it, a browser
 *     that cached `app.css` under an hour-long `max-age` keeps running the old stylesheet against
 *     new markup — which is exactly how a styled button turns into an unstyled one after a deploy.
 *     Changing the query makes it a different URL, so a stale entry can never be reused.
 *
 * The output goes to `.deploy/`; `firebase.json` publishes that directory. Sources stay clean, and
 * nothing generated is committed.
 *
 * Usage: node scripts/build-web.mjs [--check]
 *   --check  build into a temp path and report whether the committed sources are consistent
 */
import { createHash } from "node:crypto";
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const SOURCE = resolve("web");
const OUT = resolve(".deploy");
const CONSTELLATION_ASSETS = resolve("ui/public/constellations");
const check = process.argv.includes("--check");
const CMS_URL = (process.env.RIGEL_CMS_URL || "").trim().replace(/\/+$/, "");

function appDataDir() {
  if (process.env.RIGEL_INDEX_DIR) return process.env.RIGEL_INDEX_DIR;
  if (process.platform === "win32") {
    return join(process.env.APPDATA || join(homedir(), "AppData", "Roaming"), "Rigel");
  }
  if (process.platform === "darwin") {
    return join(homedir(), "Library", "Application Support", "Rigel");
  }
  return join(process.env.XDG_DATA_HOME || join(homedir(), ".local", "share"), "rigel");
}

function fromCloudJson() {
  const path = join(appDataDir(), "cloud.json");
  if (!existsSync(path)) return null;
  try {
    const config = JSON.parse(readFileSync(path, "utf8"));
    if (!config.project_id || !config.api_key) return null;
    return { projectId: config.project_id, apiKey: config.api_key };
  } catch {
    return null;
  }
}

const config =
  process.env.RIGEL_FIREBASE_PROJECT_ID && process.env.RIGEL_FIREBASE_API_KEY
    ? {
        projectId: process.env.RIGEL_FIREBASE_PROJECT_ID,
        apiKey: process.env.RIGEL_FIREBASE_API_KEY,
      }
    : fromCloudJson();

if (!config) {
  console.error(
    "No Firebase project found. Set RIGEL_FIREBASE_PROJECT_ID and RIGEL_FIREBASE_API_KEY,\n" +
      "or run `rigel cloud configure --project <id>` so cloud.json exists.",
  );
  process.exit(1);
}

if (!existsSync(join(SOURCE, "index.html"))) {
  console.error(`No site sources at ${SOURCE}`);
  process.exit(1);
}

rmSync(OUT, { recursive: true, force: true });
cpSync(SOURCE, OUT, { recursive: true });

// The window bundles these SVGs from `ui/public`; publish the same files beside the site so the
// cloud copy and the offline copy cannot drift.
if (!existsSync(CONSTELLATION_ASSETS)) {
  console.error(`No constellation assets at ${CONSTELLATION_ASSETS}`);
  process.exit(1);
}
cpSync(CONSTELLATION_ASSETS, join(OUT, "constellations"), { recursive: true });

await applyCmsContent();

const generated = `// Generated by scripts/build-web.mjs — do not edit, do not commit.
// Every value here is public: the API key ships in any Firebase web client, and firestore.rules
// is what decides who may read a document.
window.RIGEL_CONFIG = ${JSON.stringify(
  {
    ...config,
    // Popup and redirect sign-in both refuse to start without this.
    authDomain: process.env.RIGEL_FIREBASE_AUTH_DOMAIN || `${config.projectId}.firebaseapp.com`,
  },
  null,
  2,
)};
`;
writeFileSync(join(OUT, "app", "config.js"), generated);

/** One hash for the whole deploy: any change to any asset changes every URL, which is cheap here. */
function digest(files) {
  const hash = createHash("sha256");
  for (const file of files) hash.update(readFileSync(join(OUT, file)));
  return hash.digest("hex").slice(0, 10);
}

const version = digest([
  "app/app.js",
  "app/app.css",
  "app/config.js",
  "site.css",
  "site.js",
  "gtag.js",
]);

/**
 * Rewrite local asset URLs with the deploy's version, keeping both quotes exactly where they were.
 *
 * An earlier version of this dropped the closing quote, which silently turned
 * `href="/app/app.css"` into `href="/app/app.css?v=abc />` — the browser then read the rest of
 * the document as part of the attribute, so no stylesheet or script ever loaded. Quotes are
 * captured, not assumed.
 */
function stamp(html) {
  return html.replace(/(\b(?:src|href)=)("[^"]*"|'[^']*')/g, (match, attr, quoted) => {
    const quote = quoted[0];
    const value = quoted.slice(1, -1);
    // Only local files with no query yet: the gstatic modules carry their own version.
    if (!/^\/[^"'?]+\.(?:css|js)$/.test(value)) return match;
    return `${attr}${quote}${value}?v=${version}${quote}`;
  });
}

for (const page of ["index.html", "app/index.html"]) {
  const path = join(OUT, page);
  const stamped = stamp(readFileSync(path, "utf8"));
  // A swallowed quote reads as markup inside an attribute value. Refuse to publish that.
  if (/(?:src|href)="[^"]*[<>][^"]*"/.test(stamped)) {
    console.error(`refusing to write ${path}: an attribute value contains markup`);
    process.exit(1);
  }
  writeFileSync(path, stamped);
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeAttribute(value) {
  return escapeHtml(value).replace(/"/g, "&quot;");
}

function renderInline(value) {
  let out = escapeHtml(value);
  out = out.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (whole, label, href) => {
    const target = href.replace(/&amp;/g, "&");
    if (!/^(?:https:\/\/[^\s]+|\/[^\s]*)$/.test(target)) return label;
    const rel = target.startsWith("http") ? ' rel="noopener"' : "";
    return `<a href="${escapeAttribute(target)}"${rel}>${label}</a>`;
  });
  out = out.replace(/`([^`]+)`/g, "<code>$1</code>");
  out = out.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  out = out.replace(/\{\{skill_count\}\}/g, '<span data-skill-count>11,587</span>');
  return out;
}

function renderFaqAnswer(value) {
  const blocks = String(value).trim().split(/\n{2,}/);
  return blocks
    .map((block) => {
      const lines = block
        .split("\n")
        .map((line) => line.trim())
        .filter(Boolean);
      if (lines.length > 0 && lines.every((line) => line.startsWith("- "))) {
        return `<ul>${lines.map((line) => `<li>${renderInline(line.slice(2))}</li>`).join("")}</ul>`;
      }
      return `<p>${renderInline(lines.join(" "))}</p>`;
    })
    .join("\n");
}

function replaceRange(html, start, end, replacement) {
  const from = html.indexOf(start);
  const to = html.indexOf(end);
  if (from === -1 || to === -1 || to < from) return null;
  return `${html.slice(0, from + start.length)}\n${replacement}\n${html.slice(to)}`;
}

async function applyCmsContent() {
  if (!CMS_URL || check) return;
  try {
    const endpoint = new URL(`${CMS_URL}/api/faqs`);
    endpoint.search = new URLSearchParams({
      "where[published][equals]": "true",
      sort: "order",
      limit: "100",
      depth: "0",
    }).toString();
    const response = await fetch(endpoint, {
      headers: { accept: "application/json" },
      signal: AbortSignal.timeout(10_000),
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    const faqs = (Array.isArray(data.docs) ? data.docs : [])
      .map((row) => ({
        anchor: String(row.anchor || "").trim(),
        navLabel: String(row.navLabel || row.question || "").trim(),
        question: String(row.question || "").trim(),
        answer: String(row.answer || "").trim(),
      }))
      .filter(
        (row) =>
          /^[a-z0-9][a-z0-9-]*$/i.test(row.anchor) && row.question && row.answer && row.navLabel,
      );
    if (faqs.length === 0) {
      console.log("CMS: no published FAQs; keeping the static FAQ");
      return;
    }

    const path = join(OUT, "faq.html");
    const source = readFileSync(path, "utf8");
    let html = replaceRange(
      source,
      "<!-- cms:faq-nav:start -->",
      "<!-- cms:faq-nav:end -->",
      faqs
        .map(
          (faq) =>
            `        <a href="#${escapeAttribute(faq.anchor)}">${escapeHtml(faq.navLabel)}</a>`,
        )
        .join("\n"),
    );
    if (html === null) throw new Error("FAQ navigation markers are missing");
    html = replaceRange(
      html,
      "<!-- cms:faq:start -->",
      "<!-- cms:faq:end -->",
      faqs
        .map(
          (faq) =>
            `        <section class="doc-section" id="${escapeAttribute(faq.anchor)}" data-cms="faq">\n          <h2>${escapeHtml(faq.question)}</h2>\n${renderFaqAnswer(faq.answer)}\n        </section>`,
        )
        .join("\n"),
    );
    if (html === null) throw new Error("FAQ section markers are missing");
    writeFileSync(path, html);
    console.log(`CMS: injected ${faqs.length} published FAQs into ${path}`);
  } catch (error) {
    console.warn(`CMS: could not load content (${error?.message ?? error}); keeping the static FAQ`);
  }
}

if (check) {
  console.log(`built ${OUT} at version ${version} (nothing published)`);
  process.exit(0);
}

console.log(`built ${OUT}`);
console.log(`  project ${config.projectId}`);
console.log(`  asset version ${version}`);
console.log("  deploy with: npx firebase-tools deploy --only hosting --project <id>");
